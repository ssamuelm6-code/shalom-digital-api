function normalizeWord(word) {
  let next = SYNONYMS[word] || word;
  if (!SYNONYMS[word] && next.length > 3 && next.endsWith("s") && !next.endsWith("ss")) {
    next = next.slice(0, -1);
  }
  return next;
}

export function tokenize(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .split(/\s+/)
    .filter((word) => word.length > 2 && !STOP_WORDS.has(word))
    .map(normalizeWord)
    .filter((word) => word.length > 2 && !STOP_WORDS.has(word));
}

function scoreEntry(queryTokens, entry) {
  const questionTokens = new Set(tokenize(entry.question));
  const answerTokens = new Set(tokenize(entry.answer));
  const tagTokens = new Set((entry.tags || []).flatMap((tag) => tokenize(tag)));
  let score = 0;
  for (const token of queryTokens) {
    if (tagTokens.has(token)) score += 3;
    else if (questionTokens.has(token)) score += 2;
    else if (answerTokens.has(token)) score += 1;
  }
  return score;
}

const GREETING_WORDS = new Set([
  "hi", "hii", "hiii", "hello", "helo", "hallo", "hai", "hlo", "hey", "heyy", "yo",
  "greetings", "greeting", "morning", "afternoon", "evening", "salam",
  "salaam", "namaste", "namaskar", "vanakkam", "hola", "howdy",
]);

export function isGreeting(text) {
  const words = String(text || "")
    .toLowerCase()
    .replace(/[^a-z\s]/g, " ")
    .split(/\s+/)
    .filter(Boolean);

  if (!words.length || words.length > 3) return false;

  const realGreetings = words.filter((word) => GREETING_WORDS.has(word));
  if (!realGreetings.length) return false;

  return words.every((word) => GREETING_WORDS.has(word) || word === "good" || word === "there");
}

export function greetingReply(profile, entries) {
  const p = profile || defaultProfile;
  const list = Array.isArray(entries) ? entries : [];

  const welcome = list.find((entry) => {
    const tags = (entry.tags || []).map((tag) => String(tag).toLowerCase());
    const question = String(entry.question || "").toLowerCase();
    return tags.includes("welcome") || tags.includes("greeting") || /\b(welcome|greeting)\b/.test(question);
  });

  if (welcome?.answer) return welcome.answer;
  return `Hi! Welcome to ${p.businessName}. How can I help you today?`;
}

export function searchEntries(text, entries, limit = 6) {
  const queryTokens = tokenize(text);
  if (!queryTokens.length) return [];
  return entries
    .map((entry) => ({ entry, score: scoreEntry(queryTokens, entry) }))
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((item) => item.entry);
}

export function buildSystemPrompt(profile, entries, relevantEntries) {
  const p = profile || defaultProfile;
  const faq = (relevantEntries && relevantEntries.length ? relevantEntries : entries) || [];

  const faqText = faq
    .map((entry, index) => `${index + 1}. Q: ${entry.question}\n   A: ${entry.answer}`)
    .join("\n");

  return [
    `You are the WhatsApp customer support assistant for ${p.businessName}.`,
    "",
    "BUSINESS INFORMATION",
    `- Name: ${p.businessName}`,
    p.description ? `- About: ${p.description}` : "",
    p.hours ? `- Opening hours: ${p.hours}` : "",
    p.contact ? `- Contact: ${p.contact}` : "",
    p.website ? `- Website: ${p.website}` : "",
    p.extra ? `- Other details: ${p.extra}` : "",
    "",
    "TRAINING / FAQ",
    faqText || "(no FAQ entries yet)",
    "",
    "RULES",
    `- Write in a ${p.tone || "friendly and professional"} tone.`,
    "- Answer ONLY using the business information and FAQ above.",
    "- If the answer is not available, politely say you'll connect them with the team and share the contact details.",
    "- Reply in the same language the customer used.",
    "- Keep answers short and WhatsApp-friendly. Do not use markdown like **bold** or headings.",
    "- Never invent prices, policies, dates or facts.",
    "- Do not mention that you are an AI language model.",
  ]
    .filter((line) => line !== "")
    .join("\n");
}

const THANKS_WORDS = new Set([
  "thanks", "thank", "thankyou", "thanku", "thx", "appreciate", "appreciated", "grateful",
]);
const FAREWELL_WORDS = new Set([
  "bye", "goodbye", "cya", "tata", "later", "goodnight",
]);
const ACK_WORDS = new Set([
  "ok", "okay", "k", "cool", "great", "nice", "awesome", "fine", "sure",
]);

function wordsOf(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/[^a-z\s]/g, " ")
    .split(/\s+/)
    .filter(Boolean);
}

function isThanks(text) {
  const words = wordsOf(text);
  return words.length <= 6 && words.some((word) => THANKS_WORDS.has(word));
}

function isFarewell(text) {
  const words = wordsOf(text);
  if (words.length > 6) return false;
  if (words.some((word) => FAREWELL_WORDS.has(word))) return true;
  if (words.includes("see") && words.includes("you")) return true;
  return words.includes("good") && words.includes("night");
}

function isAcknowledgement(text) {
  const words = wordsOf(text);
  return words.length > 0 && words.length <= 2 && words.every((word) => ACK_WORDS.has(word));
}

function isIdentityQuestion(text) {
  const value = String(text || "").toLowerCase();
  return /\b(are you|r u|is this|this is)\b.*\b(bot|robot|human|real|ai|chatbot|automated|machine|person)\b/.test(
    value
  );
}

export function smallTalkReply(profile, text) {
  const p = profile || defaultProfile;

  if (isThanks(text)) {
    return `You're welcome! If you need anything else, we're here. You can also reach our team at ${
      p.contact || "our contact details"
    }.`;
  }

  if (isFarewell(text)) {
    return `Thank you for reaching out to ${p.businessName}! Have a great day. You can reach us anytime at ${
      p.contact || "our contact details"
    }.`;
  }

  if (isIdentityQuestion(text)) {
    return `I'm ${p.businessName}'s automated WhatsApp assistant. I can help with services, pricing, offers and booking a free audit. For anything specific, our team is available at ${
      p.contact || "our contact details"
    }.`;
  }

  if (isAcknowledgement(text)) {
    return "Great! Is there anything else I can help you with?";
  }

  return "";
}

export function isServicesQuestion(text) {
  const value = String(text || "").toLowerCase();
  return (
    /\b(what|which)\b.*\bservices?\b/.test(value) ||
    /\bwhat\s+(do|can)\s+(you|u)\s+(offer|provide|do|help)\b/.test(value) ||
    /\bhow\s+(can|do)\s+(you|u)\s+help\b/.test(value)
  );
}

export function servicesReply(entries) {
  const list = Array.isArray(entries) ? entries : [];
  const entry = list.find((item) =>
    (item.tags || []).some((tag) => ["services", "service"].includes(String(tag).toLowerCase()))
  );
  return entry?.answer || "";
}

export function fallbackReply(profile, entries, text) {
  const p = profile || defaultProfile;
  if (isGreeting(text)) return greetingReply(p, entries);
  const smallTalk = smallTalkReply(p, text);
  if (smallTalk) return smallTalk;
  if (isServicesQuestion(text)) {
    const services = servicesReply(entries);
    if (services) return services;
  }
  const matches = searchEntries(text, entries, 1);
  if (matches.length) return matches[0].answer;
  return `Thanks for reaching out! I don't have that information on hand right now. Please contact us at ${
    p.contact || "our support team"
  } and we'll be happy to help.`;
}
